import { prisma } from "./prisma";
import type { AiGenerationStatus, Prisma, Priority } from "@prisma/client";

// The normalized, validated tree the service hands to approveAndCreate.
export type ApprovedTestCase = {
  title: string;
  preconditions: string | null;
  steps: { stepNumber: number; action: string; expectedResult: string }[];
  expectedResult: string | null;
  priority: Priority;
};

export type ApprovedStory = {
  title: string;
  description: string | null;
  acceptanceCriteria: string | null;
  edgeCases: string | null;
  priority: Priority;
  storyPoints: number | null;
  testCases: ApprovedTestCase[];
};

export type ApprovedFeature = {
  title: string;
  description: string | null;
  stories: ApprovedStory[];
};

export type ApprovedEpic = {
  title: string;
  description: string | null;
  features: ApprovedFeature[];
};

const listInclude = {
  generatedBy: { select: { id: true, name: true } },
  _count: { select: { createdEntities: true } },
} satisfies Prisma.AiGenerationInclude;

export type AiGenerationListRow = Prisma.AiGenerationGetPayload<{
  include: typeof listInclude;
}>;

export const aiGenerationRepository = {
  // Per-project AI configuration (mode/provider/model/approval rule).
  getConfig(projectId: string) {
    return prisma.projectAiConfig.findUnique({ where: { projectId } });
  },

  createDraft(input: {
    projectId: string;
    generatedById: string;
    provider: string;
    model: string;
    promptVersion: number;
    inputText: string;
    generatedJson: Prisma.InputJsonValue;
    tokenCount: number;
  }) {
    return prisma.aiGeneration.create({
      data: {
        projectId: input.projectId,
        generatedById: input.generatedById,
        provider: input.provider,
        model: input.model,
        promptVersion: input.promptVersion,
        inputSource: "pasted_text",
        inputText: input.inputText,
        generatedJson: input.generatedJson,
        tokenCount: input.tokenCount,
        status: "DRAFT",
      },
    });
  },

  findById(id: string) {
    return prisma.aiGeneration.findUnique({ where: { id } });
  },

  listForProject(projectId: string, status?: AiGenerationStatus) {
    return prisma.aiGeneration.findMany({
      where: { projectId, ...(status ? { status } : {}) },
      orderBy: { createdAt: "desc" },
      include: listInclude,
    });
  },

  // Rejects a draft, recording who reviewed it and an optional note.
  setRejected(input: { id: string; reviewerId: string; note: string | null }) {
    return prisma.aiGeneration.update({
      where: { id: input.id },
      data: {
        status: "REJECTED",
        reviewedById: input.reviewerId,
        reviewNote: input.note,
        rejectedAt: new Date(),
      },
    });
  },

  // Creates every approved epic/feature/story/test case, links them back to the
  // generation via AiGeneratedEntity, marks the generation APPROVED, and emits
  // the outbox event — all in one transaction. Work item keys are generated by
  // atomically incrementing project.nextItemNumber, same as workItemRepository.
  async approveAndCreate(input: {
    generationId: string;
    projectId: string;
    actorUserId: string;
    epics: ApprovedEpic[];
  }) {
    return prisma.$transaction(async (tx) => {
      // New stories land in the project's first board column.
      const columns = await tx.workflowStatus.findMany({
        where: { projectId: input.projectId },
        orderBy: { displayOrder: "asc" },
        select: { id: true },
      });
      if (columns.length === 0) {
        throw new Error("Project has no workflow statuses.");
      }
      const statusId = columns[0].id;

      const links: { entityType: string; entityId: string }[] = [];
      const counts = { epics: 0, features: 0, stories: 0, testCases: 0 };

      for (const epic of input.epics) {
        const createdEpic = await tx.epic.create({
          data: {
            projectId: input.projectId,
            title: epic.title,
            description: epic.description,
          },
          select: { id: true },
        });
        links.push({ entityType: "Epic", entityId: createdEpic.id });
        counts.epics++;

        for (const feature of epic.features) {
          const createdFeature = await tx.feature.create({
            data: {
              projectId: input.projectId,
              epicId: createdEpic.id,
              title: feature.title,
              description: feature.description,
            },
            select: { id: true },
          });
          links.push({ entityType: "Feature", entityId: createdFeature.id });
          counts.features++;

          for (const story of feature.stories) {
            const project = await tx.project.update({
              where: { id: input.projectId },
              data: { nextItemNumber: { increment: 1 } },
              select: { key: true, nextItemNumber: true },
            });
            const itemKey = `${project.key}-${project.nextItemNumber - 1}`;

            const createdItem = await tx.workItem.create({
              data: {
                projectId: input.projectId,
                statusId,
                itemKey,
                type: "STORY",
                title: story.title,
                description: story.description,
                acceptanceCriteria: story.acceptanceCriteria,
                edgeCases: story.edgeCases,
                priority: story.priority,
                storyPoints: story.storyPoints,
                reporterId: input.actorUserId,
                epicId: createdEpic.id,
                featureId: createdFeature.id,
              },
              select: { id: true },
            });
            links.push({ entityType: "WorkItem", entityId: createdItem.id });
            counts.stories++;

            for (let i = 0; i < story.testCases.length; i++) {
              const tc = story.testCases[i];
              const createdTc = await tx.testCase.create({
                data: {
                  workItemId: createdItem.id,
                  createdById: input.actorUserId,
                  title: tc.title,
                  preconditions: tc.preconditions,
                  steps: tc.steps,
                  expectedResult: tc.expectedResult,
                  priority: tc.priority,
                  status: "DRAFT",
                  aiGenerationId: input.generationId,
                  sortOrder: i,
                },
                select: { id: true },
              });
              links.push({ entityType: "TestCase", entityId: createdTc.id });
              counts.testCases++;
            }
          }
        }
      }

      await tx.aiGeneratedEntity.createMany({
        data: links.map((l) => ({
          generationId: input.generationId,
          entityType: l.entityType,
          entityId: l.entityId,
        })),
      });

      await tx.aiGeneration.update({
        where: { id: input.generationId },
        data: {
          status: "APPROVED",
          reviewedById: input.actorUserId,
          approvedAt: new Date(),
        },
      });

      await tx.outboxEvent.create({
        data: {
          eventType: "ai_generation_approved",
          payload: {
            generationId: input.generationId,
            projectId: input.projectId,
            actorUserId: input.actorUserId,
            counts,
          },
        },
      });

      return counts;
    });
  },
};
